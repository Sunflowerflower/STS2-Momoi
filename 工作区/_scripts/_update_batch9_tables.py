# dump 里还沿用旧卡名
DUMP_ALIAS = {
    "来自大师们的援助": "来自工程部的援助",
    "来自骇客们的协助": "来自真理部的协助",
}


def main():
    dry = "--dry" in sys.argv
    os.makedirs(BAKDIR, exist_ok=True)
    ts = datetime.datetime.now().strftime("%Y-%m-%d_%H%M")
    if not dry:
        shutil.copy2(XL, os.path.join(BAKDIR, "STS2Momoi_%s_pre_batch9.xlsx" % ts))
    wb = openpyxl.load_workbook(XL)
    ws = wb["卡牌"]
    row_of = {}
    for r in range(3, ws.max_row + 1):
        v = ws.cell(row=r, column=2).value
        if v:
            row_of.setdefault(str(v), r)

    n = 0
    for name, col, txt in FULL:
        r = row_of.get(name)
        if r is None:
            print("  !! xlsx 未找到:", name); continue
        ws.cell(row=r, column=col).value = txt
        n += 1
    for name, col, old, new in SUB:
        r = row_of.get(name)
        if r is None:
            print("  !! xlsx 未找到:", name); continue
        cur = ws.cell(row=r, column=col).value
        if cur is None:
            print("  !! 空单元格:", name, col); continue
        if old not in cur:
            print("  !! 未匹配:", name, col, "|", old[:40]); continue
        ws.cell(row=r, column=col).value = cur.replace(old, new)
        n += 1
    if not dry:
        wb.save(XL)
    print("xlsx 改动 %d 处" % n)

    # ── 设计 dump：按 xlsx 的新值重写对应条目
    text = open(DUMPF, encoding="utf-8").read()
    m = 0
    for name in sorted(set([x[0] for x in FULL] + [x[0] for x in SUB])):
        r = row_of.get(name)
        if r is None:
            continue
        desc = ws.cell(row=r, column=7).value or ""
        descUp = ws.cell(row=r, column=8).value or ""
        note = ws.cell(row=r, column=10).value
        dna = DUMP_ALIAS.get(name, name)
        pat = re.compile(r"### \[(\d+)\] " + re.escape(dna) + r" \|.*?\n(?:(?:desc|descUp|note):.*\n?)*")
        mm = pat.search(text)
        if not mm:
            print("  -- dump 无此条（跳过）:", name); continue
        head = mm.group(0).splitlines()[0]
        lines = [head,
                 "desc: " + desc.replace(NL, AR),
                 "descUp: " + descUp.replace(NL, AR)]
        if note:
            lines.append("note: " + str(note).replace(NL, AR))
        text = text[:mm.start()] + NL.join(lines) + NL + NL + text[mm.end():]
        m += 1
    if not dry:
        open(DUMPF, "w", encoding="utf-8").write(text)
    print("dump 改写 %d 条" % m, "[dry-run]" if dry else "已写入")


if __name__ == "__main__":
    main()
