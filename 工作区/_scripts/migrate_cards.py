def main():
    # 备份原文件
    shutil.copy2(XLSX, XLSX + ".bak")
    wb = openpyxl.load_workbook(XLSX)
    ws = wb["卡牌"]

    start_row = ws.max_row + 1  # 现有 41 行后追加（第 42 行起）
    font = Font(name="宋体", size=11)
    wrap = Alignment(wrap_text=True, vertical="center")

    for i, (name, ctype, rarity, cost, upcost, desc, updesc, tags, note) in enumerate(CARDS):
        r = start_row + i
        values = [None, name, ctype, rarity, cost, upcost, desc, updesc, tags, note, None]
        for col_idx, v in enumerate(values, start=1):
            cell = ws.cell(row=r, column=col_idx, value=v)
            cell.font = font
            if col_idx in (7, 8, 10):  # 卡牌描述/升级后描述/备注 自动换行
                cell.alignment = wrap

        # 行高按最长文本行数估算（与现有行风格一致：约 9.4/行）
        lines = 1
        for text in (desc, updesc, note):
            if text:
                lines = max(lines, text.count("\n") + 1)
        ws.row_dimensions[r].height = max(18, min(lines * 9.4 + 4, 400))

    wb.save(XLSX)
    print(f"已写入 {len(CARDS)} 张卡，起始行 {start_row}，共 {start_row + len(CARDS) - 1} 行。")


if __name__ == "__main__":
    main()
